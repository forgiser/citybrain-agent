import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import {
  createDefaultWorkspaceManifest,
  getWorkspaceManifestPath,
  readWorkspaceManifest,
  writeWorkspaceManifest,
} from "./sandbox-policy.js";

/**
 * CityBrain project workspace. The project root is user selected, while the
 * sandbox workspace lives under <projectDir>/citybrain.
 */
export const WORKSPACE_DIR_NAME = "citybrain";

const WORKSPACE_DIRECTORIES = [
  "artifacts/process",
  "artifacts/result",
  ".internal/tmp",
  ".internal/logs",
  ".internal/state",
] as const;

export interface WorkspaceInfo {
  /** Absolute project root selected by the user. */
  projectDir: string;
  /** Absolute workspace root: <projectDir>/citybrain. */
  workspaceDir: string;
  /** Paths created or materialized during this ensure call. */
  created: string[];
  /** Whether the workspace directory existed before this call. */
  alreadyInitialized: boolean;
}

export function getWorkspaceDir(projectDir: string): string {
  return join(resolve(projectDir), WORKSPACE_DIR_NAME);
}

export function isWorkspaceInitialized(projectDir: string): boolean {
  return existsSync(getWorkspaceDir(projectDir));
}

/**
 * Idempotently create or migrate the workspace skeleton. User-authored files
 * are never overwritten.
 */
export function ensureWorkspace(projectDir: string): WorkspaceInfo {
  const projectDirResolved = resolve(projectDir);
  const workspaceDir = getWorkspaceDir(projectDirResolved);
  const alreadyInitialized = existsSync(workspaceDir);
  const created: string[] = [];

  ensureDirectory(workspaceDir, created);
  for (const relative of WORKSPACE_DIRECTORIES) {
    ensureDirectory(join(workspaceDir, relative), created);
  }

  ensureAgentsFile(workspaceDir, basename(projectDirResolved), created);
  ensureProfileFile(workspaceDir, basename(projectDirResolved), created);
  ensureManifest(workspaceDir, projectDirResolved, created);

  return { projectDir: projectDirResolved, workspaceDir, created, alreadyInitialized };
}

function ensureDirectory(path: string, created: string[]): void {
  if (existsSync(path)) return;
  mkdirSync(path, { recursive: true });
  created.push(path);
}

function ensureAgentsFile(workspaceDir: string, projectName: string, created: string[]): void {
  const agentsPath = join(workspaceDir, "AGENTS.md");
  if (existsSync(agentsPath)) return;

  const legacyAgentPath = join(workspaceDir, "AGENT.md");
  const content = existsSync(legacyAgentPath)
    ? readFileSync(legacyAgentPath, "utf8")
    : defaultAgentsMd(projectName);
  writeFileSync(agentsPath, content, "utf8");
  created.push(agentsPath);
}

function ensureProfileFile(workspaceDir: string, projectName: string, created: string[]): void {
  const profilePath = join(workspaceDir, "profile.md");
  if (existsSync(profilePath)) return;

  writeFileSync(profilePath, defaultProfileMd(projectName), "utf8");
  created.push(profilePath);
}

function ensureManifest(workspaceDir: string, projectDir: string, created: string[]): void {
  const manifestPath = getWorkspaceManifestPath(workspaceDir);
  if (existsSync(manifestPath)) return;

  const legacyOrDefaultManifest = readWorkspaceManifest(workspaceDir, projectDir);
  writeWorkspaceManifest({
    ...createDefaultWorkspaceManifest(workspaceDir, projectDir),
    ...legacyOrDefaultManifest,
    workspaceRoot: workspaceDir,
    projectDir,
    updatedAt: new Date().toISOString(),
  });
  created.push(manifestPath);
}

function defaultAgentsMd(name: string): string {
  return [
    "# AGENTS.md",
    "",
    `${name} CityBrain project guidance. Add project goals, data sources, naming rules, CRS requirements, and output conventions here.`,
    "",
    "## Goals",
    "",
    "- ",
    "",
    "## Data",
    "",
    "- ",
    "",
    "## Constraints",
    "",
    "- Coordinate reference system:",
    "- Output format:",
    "- Naming convention:",
    "",
  ].join("\n");
}

function defaultProfileMd(name: string): string {
  return [
    "# profile.md",
    "",
    `Workspace profile for ${name}. This file is generated by the CityBrain Harness profile workflow and is safe for users to read.`,
    "",
    "## Data Sources",
    "",
    "- No source data has been profiled yet.",
    "",
    "## Process Artifacts",
    "",
    "- No process artifacts have been recorded yet.",
    "",
    "## Result Artifacts",
    "",
    "- No result artifacts have been recorded yet.",
    "",
    "## Notes",
    "",
    "- The profile is a derived summary. The filesystem and workspace.json remain the source of truth.",
    "",
  ].join("\n");
}
